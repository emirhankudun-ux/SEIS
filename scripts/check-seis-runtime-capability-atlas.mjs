#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";

const ROOT = process.cwd();
const args = new Set(process.argv.slice(2));
const WRITE = args.has("--write");
const failures = [];

const ATLAS_PATH = "data/seis-runtime-capability-atlas.json";
const WEB_ASSET_PATH = "apps/web/seis-runtime-capability-atlas.js";
const HTML_PATH = "apps/web/seis-linux-replica.html";
const BROWSER_SMOKE_PATH = "scripts/check-seis-linux-replica-browser-smoke.mjs";
const SERVICE_WORKER_PATH = "apps/web/service-worker.js";
const ROUTES_PATH = "apps/web/src/config/routes.json";

const requiredProductModules = [
  "desktop-os",
  "ai-core",
  "search",
  "code-ide",
  "design-studio",
  "cloud",
  "store",
  "music",
  "launchpad",
  "files",
  "terminal-ssh",
  "website",
  "agents",
  "plugins",
  "command-center"
];

const requiredRuntimeBoundary = {
  currentLevel: "status-and-plan-only",
  backgroundAutomation: "disabled",
  writeExecution: "disabled",
  credentialAccess: "forbidden",
  externalMutation: "requires-explicit-human-approval"
};

function ensure(condition, message) {
  if (!condition) failures.push(message);
}

function readText(relativePath) {
  return fs.readFileSync(path.join(ROOT, relativePath), "utf8");
}

function readJson(relativePath) {
  try {
    return JSON.parse(readText(relativePath));
  } catch (error) {
    ensure(false, `${relativePath} must be readable JSON: ${error.message}`);
    return null;
  }
}

function exists(relativePath) {
  return fs.existsSync(path.join(ROOT, relativePath));
}

function pathKind(relativePath) {
  if (typeof relativePath !== "string") return "missing";
  try {
    const stats = fs.statSync(path.join(ROOT, relativePath));
    if (stats.isFile()) return "file";
    if (stats.isDirectory()) return "directory";
    return "other";
  } catch {
    return "missing";
  }
}

function arraysEqual(a, b) {
  if (!Array.isArray(a) || !Array.isArray(b) || a.length !== b.length) return false;
  return a.every((item, index) => item === b[index]);
}

function setEqual(a, b) {
  const left = new Set(a);
  const right = new Set(b);
  if (left.size !== right.size) return false;
  for (const item of left) {
    if (!right.has(item)) return false;
  }
  return true;
}

function unique(values) {
  return Array.from(new Set(values));
}

function kebab(value) {
  return String(value || "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function ensureExistingPath(relativePath, label) {
  const kind = pathKind(relativePath);
  ensure(kind === "file" || kind === "directory", `${label} path does not exist: ${relativePath}`);
}

function renderWebAsset(atlas) {
  return [
    "// Generated by scripts/check-seis-runtime-capability-atlas.mjs from data/seis-runtime-capability-atlas.json.",
    "// Do not edit this file manually; edit the JSON source and rerun the generator.",
    "(function(){",
    `  window.SEIS_RUNTIME_CAPABILITY_ATLAS = ${JSON.stringify(atlas, null, 2)};`,
    "})();",
    ""
  ].join("\n");
}

function validateNoSecretLikeValues(atlas) {
  const source = JSON.stringify(atlas);
  const patterns = [
    /sk-[A-Za-z0-9_-]{16,}/,
    /-----BEGIN [A-Z ]*PRIVATE KEY-----/,
    /AKIA[0-9A-Z]{16}/,
    /xox[baprs]-[A-Za-z0-9-]{10,}/
  ];
  for (const pattern of patterns) {
    ensure(!pattern.test(source), `atlas contains a secret-like value matching ${pattern}`);
  }
}

function validatePaths(atlas) {
  for (const relativePath of atlas.sourceEvidence || []) {
    ensureExistingPath(relativePath, "sourceEvidence");
  }

  for (const module of atlas.productModules || []) {
    for (const evidence of module.evidence || []) {
      ensureExistingPath(evidence, `module ${module.id} evidence`);
    }
  }

  for (const lane of atlas.lanes || []) {
    for (const field of ["repoRoot", "sourceMirror", "skillPath", "sourceSkillPath"]) {
      ensureExistingPath(lane[field], `lane ${lane.laneId} ${field}`);
    }
    for (const gate of lane.qualityGates || []) {
      ensure(/^npm run [a-z0-9:_-]+/.test(gate), `lane ${lane.laneId} quality gate must be an npm script: ${gate}`);
    }
  }

  for (const task of atlas.dryRunQueue || []) {
    for (const evidence of task.evidence || []) {
      ensureExistingPath(evidence, `task ${task.id} evidence`);
    }
  }
}

function validateSourceRegistries(atlas) {
  const specialist = readJson("data/seis-specialist-plugins-2026-06-12.json");
  const operating = readJson("data/seis-operating-identities.json");
  const runtime = readJson("content/development/seis-ai-core-subagent-runtime-fixtures.json");
  const roles = readJson("content/development/seis-ai-core-agent-role-schema.json");
  const dryRun = readJson("content/development/seis-ai-core-dry-run-task-queue.json");
  const secondBrain = readJson("content/development/seis-second-brain-system.json");

  if (!specialist || !operating || !runtime || !roles || !dryRun || !secondBrain) return;

  ensure(atlas.mode === specialist.mode, "atlas mode must match specialist plugin manifest mode");
  ensure(atlas.mode === "single-seis-agent-embedded-lanes", "atlas must keep single-agent embedded lane mode");
  ensure(operating.identities?.some((identity) => identity.installId === "seis-ai-agent@seis-repo"), "operating identities must expose SEIS-Agent primary install id");

  for (const [key, expected] of Object.entries(requiredRuntimeBoundary)) {
    ensure(atlas.runtimeBoundary?.[key] === expected, `runtimeBoundary.${key} must be ${expected}`);
    ensure(runtime.runtimeBoundary?.[key] === expected, `runtime fixture runtimeBoundary.${key} must be ${expected}`);
  }
  ensure(atlas.runtimeBoundary?.liveMcpSession === "not-started-from-browser", "browser atlas must not claim a live MCP session");
  ensure(atlas.runtimeBoundary?.providerCalls === "disabled", "browser atlas must not claim provider calls");

  const atlasLaneIds = (atlas.lanes || []).map((lane) => lane.laneId);
  ensure(setEqual(atlasLaneIds, runtime.roleSchema?.requiredLaneIds || []), "atlas laneIds must match runtime required laneIds");
  ensure(setEqual((atlas.lanes || []).map((lane) => lane.roleId), runtime.roleSchema?.requiredRoleIds || []), "atlas roleIds must match runtime required roleIds");

  const registryByPlugin = new Map((specialist.plugins || []).map((plugin) => [plugin.name, plugin]));
  for (const lane of atlas.lanes || []) {
    const plugin = registryByPlugin.get(lane.pluginName);
    ensure(Boolean(plugin), `specialist registry missing plugin for lane ${lane.laneId}: ${lane.pluginName}`);
    if (!plugin) continue;
    ensure(plugin.repoRoot === lane.repoRoot, `lane ${lane.laneId} repoRoot must match specialist registry`);
    ensure(plugin.sourceMirror === lane.sourceMirror, `lane ${lane.laneId} sourceMirror must match specialist registry`);
    ensure(plugin.installId === lane.installId, `lane ${lane.laneId} installId must match specialist registry`);
    ensure(plugin.embeddedInstallId === lane.embeddedInstallId, `lane ${lane.laneId} embeddedInstallId must match specialist registry`);
    ensure(plugin.mcpServer === lane.mcpServer, `lane ${lane.laneId} mcpServer must match specialist registry`);
    ensure(arraysEqual(plugin.tools || [], lane.tools || []), `lane ${lane.laneId} tools must match specialist registry`);
    ensure(plugin.skill === lane.skillPath.replace(`${lane.repoRoot}/`, ""), `lane ${lane.laneId} embedded skill path must match specialist registry`);

    const sourceManifestPath = `${lane.sourceMirror}/.codex-plugin/plugin.json`;
    const sourceManifest = readJson(sourceManifestPath);
    if (sourceManifest) {
      const sourceCapabilities = new Set(sourceManifest.interface?.capabilities || []);
      for (const capability of lane.capabilities || []) {
        ensure(sourceCapabilities.has(capability), `lane ${lane.laneId} capability is not in ${sourceManifestPath}: ${capability}`);
      }
    }

    if (lane.laneId !== "seis") {
      const sourceMcp = readJson(`${lane.sourceMirror}/.mcp.json`);
      ensure(sourceMcp?.mcpServers?.[lane.mcpServer]?.command === "node", `lane ${lane.laneId} source MCP manifest must expose ${lane.mcpServer}`);
    }
  }

  const roleById = new Map((roles.roles || []).map((role) => [role.id, role]));
  for (const lane of atlas.lanes || []) {
    const role = roleById.get(lane.roleId);
    ensure(Boolean(role), `role schema missing ${lane.roleId}`);
    if (role) {
      ensure(role.laneId === lane.laneId, `role ${lane.roleId} laneId must be ${lane.laneId}`);
      ensure(role.authority === "plan-only", `role ${lane.roleId} must remain plan-only`);
    }
  }

  const atlasAgentNames = (atlas.agentRoster || []).map((agent) => agent.name);
  const sourceAgentNames = (secondBrain.autonomousAgentRoster || []).map((agent) => agent.agent);
  ensure(setEqual(atlasAgentNames, sourceAgentNames), "atlas agentRoster must match second brain autonomousAgentRoster names");
  for (const sourceAgent of secondBrain.autonomousAgentRoster || []) {
    const atlasAgent = (atlas.agentRoster || []).find((agent) => agent.name === sourceAgent.agent);
    ensure(atlasAgent?.status === sourceAgent.status, `agent ${sourceAgent.agent} status must match second brain roster`);
    ensure(atlasAgent?.duty === sourceAgent.duty, `agent ${sourceAgent.agent} duty must match second brain roster`);
  }

  ensure(dryRun.status === "dry-run-only", "source dry-run queue must remain dry-run-only");
}

function validateAtlasShape(atlas) {
  ensure(atlas.id === "seis-runtime-capability-atlas", "atlas id changed");
  ensure(atlas.status === "browser-local-source-backed-catalog", "atlas status must remain browser-local-source-backed-catalog");

  const moduleIds = (atlas.productModules || []).map((module) => module.id);
  ensure(moduleIds.length >= 15, `expected at least 15 product modules, found ${moduleIds.length}`);
  ensure(moduleIds.every((id) => id === kebab(id)), "all product module ids must be kebab-case");
  ensure(unique(moduleIds).length === moduleIds.length, "product module ids must be unique");
  for (const moduleId of requiredProductModules) {
    ensure(moduleIds.includes(moduleId), `productModules missing ${moduleId}`);
  }

  const laneIds = (atlas.lanes || []).map((lane) => lane.laneId);
  ensure(unique(laneIds).length === laneIds.length, "lane ids must be unique");
  ensure(laneIds.length === 5, `expected exactly five embedded lanes, found ${laneIds.length}`);

  const agentIds = (atlas.agentRoster || []).map((agent) => agent.id);
  ensure(agentIds.length >= 13, `expected at least 13 source-backed agents, found ${agentIds.length}`);
  ensure(agentIds.every((id) => id === kebab(id)), "all agent ids must be kebab-case");
  ensure(unique(agentIds).length === agentIds.length, "agent ids must be unique");

  const coveredLaneAgentIds = unique((atlas.lanes || []).flatMap((lane) => lane.agentIds || []));
  ensure(setEqual(coveredLaneAgentIds, agentIds), "every source-backed agent must be assigned to at least one lane and no unknown agent may be assigned");

  const coveredLaneModuleIds = unique((atlas.lanes || []).flatMap((lane) => lane.moduleIds || []));
  for (const moduleId of coveredLaneModuleIds) {
    ensure(moduleIds.includes(moduleId), `lane module coverage references unknown module ${moduleId}`);
  }

  const permissionLevels = ["read-only", "plan-only", "write-gated", "external-gated", "forbidden"];
  const states = ["queued", "assigned", "running", "awaiting-approval", "cancelled", "failed", "validated", "archived"];
  const taskIds = (atlas.dryRunQueue || []).map((task) => task.id);
  ensure(taskIds.length >= agentIds.length, `expected at least one dry-run task per agent, found ${taskIds.length} tasks for ${agentIds.length} agents`);
  ensure(taskIds.every((id) => id === kebab(id)), "dry-run task ids must be kebab-case");
  ensure(unique(taskIds).length === taskIds.length, "dry-run task ids must be unique");

  const taskAgentIds = unique((atlas.dryRunQueue || []).map((task) => task.agentId));
  ensure(setEqual(taskAgentIds, agentIds), "dryRunQueue must cover every source-backed agent exactly through known agent ids");

  const taskModuleIds = unique((atlas.dryRunQueue || []).flatMap((task) => task.modules || []));
  for (const moduleId of moduleIds) {
    ensure(taskModuleIds.includes(moduleId), `dryRunQueue does not cover product module ${moduleId}`);
  }
  for (const task of atlas.dryRunQueue || []) {
    ensure(agentIds.includes(task.agentId), `task ${task.id} references unknown agent ${task.agentId}`);
    ensure(laneIds.includes(task.laneId), `task ${task.id} references unknown lane ${task.laneId}`);
    ensure(permissionLevels.includes(task.permissionLevel), `task ${task.id} has invalid permissionLevel ${task.permissionLevel}`);
    ensure(task.executionMode === "dry-run-only", `task ${task.id} must be dry-run-only`);
    ensure(states.includes(task.state), `task ${task.id} has invalid state ${task.state}`);
    ensure(Array.isArray(task.modules) && task.modules.length > 0, `task ${task.id} must declare modules`);
    ensure(Array.isArray(task.evidence) && task.evidence.length > 0, `task ${task.id} must declare evidence`);
    for (const moduleId of task.modules || []) {
      ensure(moduleIds.includes(moduleId), `task ${task.id} references unknown module ${moduleId}`);
    }
  }
}

function validateWebAsset(atlas) {
  const expected = renderWebAsset(atlas);
  const outputPath = path.join(ROOT, WEB_ASSET_PATH);

  if (WRITE) {
    fs.writeFileSync(outputPath, expected);
  } else {
    ensure(exists(WEB_ASSET_PATH), `missing generated web asset: ${WEB_ASSET_PATH}; run node scripts/check-seis-runtime-capability-atlas.mjs --write`);
  }

  if (!exists(WEB_ASSET_PATH)) return;
  const actual = readText(WEB_ASSET_PATH);
  ensure(actual === expected, `${WEB_ASSET_PATH} is out of sync with ${ATLAS_PATH}`);

  const sandbox = { window: {} };
  try {
    vm.runInNewContext(actual, sandbox, { timeout: 1000 });
    ensure(JSON.stringify(sandbox.window.SEIS_RUNTIME_CAPABILITY_ATLAS) === JSON.stringify(atlas), "generated web asset did not expose the exact atlas JSON");
  } catch (error) {
    ensure(false, `generated web asset could not be evaluated: ${error.message}`);
  }
}

function validateHtmlWiring(atlas) {
  if (!exists(HTML_PATH)) {
    ensure(false, `missing Linux Replica HTML: ${HTML_PATH}`);
    return;
  }

  const html = readText(HTML_PATH);
  const browserSmoke = exists(BROWSER_SMOKE_PATH) ? readText(BROWSER_SMOKE_PATH) : "";
  const serviceWorker = exists(SERVICE_WORKER_PATH) ? readText(SERVICE_WORKER_PATH) : "";
  const routes = exists(ROUTES_PATH) ? readJson(ROUTES_PATH) : null;

  ensure(/<script src="\.\/seis-runtime-capability-atlas\.js"(?: defer)?><\/script>/.test(html), "Linux Replica must load the runtime capability atlas asset");
  ensure(serviceWorker.includes("./seis-runtime-capability-atlas.js"), "service worker must precache the runtime capability atlas asset");
  ensure(
    routes?.routes?.find((route) => route.path === "/seis-linux-replica.html")?.sections?.includes("capability-atlas"),
    "routes.json must register the Linux Replica capability-atlas section"
  );
  ensure(html.includes('["capability-atlas"'), "BASE_APP_ENTRIES must register capability-atlas");
  ensure(html.includes("renderCapabilityAtlas"), "Linux Replica must define renderCapabilityAtlas");
  ensure(html.includes("data-capability-atlas"), "Capability Atlas app must expose a data-capability-atlas marker");
  ensure(html.includes("data-capability-lane"), "Capability Atlas app must render source-backed lane cards");
  ensure(html.includes("data-capability-agent"), "Capability Atlas app must render source-backed agent cards");
  ensure(html.includes("data-capability-task"), "Capability Atlas app must render dry-run task cards");
  ensure(html.includes("capabilities:()=>"), "terminal commands must expose capability atlas output");
  ensure(html.includes("capabilityAtlas:()=>"), "diagnostics must expose capability atlas counts");
  ensure(html.includes("window.SEIS_RUNTIME_CAPABILITY_ATLAS"), "Linux Replica must read the packaged runtime atlas");

  ensure(browserSmoke.includes("seis-runtime-capability-atlas.js"), "browser smoke static contract must require the capability atlas asset");
  ensure(browserSmoke.includes("data-capability-atlas"), "browser smoke must check capability atlas UI markers");
  ensure(browserSmoke.includes("capabilityAtlas"), "browser smoke must check capability atlas diagnostics");

  const expectedMinimumApps = 65 + 219 + 1;
  ensure(expectedMinimumApps > 284, "capability atlas should raise the minimum expected app count above the prior 284 app floor");
  ensure((atlas.lanes || []).length === 5, "atlas should expose exactly five runtime lanes to the UI");
}

const atlas = readJson(ATLAS_PATH);
if (atlas) {
  validateNoSecretLikeValues(atlas);
  validateAtlasShape(atlas);
  validatePaths(atlas);
  validateSourceRegistries(atlas);
  validateWebAsset(atlas);
  validateHtmlWiring(atlas);
}

if (failures.length > 0) {
  console.error("SEIS runtime capability atlas check failed:");
  for (const failure of failures) {
    console.error(`- ${failure}`);
  }
  process.exit(1);
}

console.log(JSON.stringify({
  ok: true,
  atlas: ATLAS_PATH,
  webAsset: WEB_ASSET_PATH,
  lanes: atlas.lanes.length,
  agents: atlas.agentRoster.length,
  modules: atlas.productModules.length,
  dryRunTasks: atlas.dryRunQueue.length,
  mode: atlas.mode,
  runtimeBoundary: atlas.runtimeBoundary.currentLevel,
  generated: WRITE
}, null, 2));
