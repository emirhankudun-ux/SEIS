import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const checkMode = process.argv.includes("--check");
const contractPath = "content/development/uixappttr-branch.json";
const runsPath = "content/development/sub-agent-runs.json";
const outputDir = "docs/development/agents";
const failures = [];
const GENERATED_NOTICE = "<!-- Generated by scripts/create-subagent-briefs.mjs. Do not edit manually. -->";

for (const file of [contractPath, runsPath]) {
  if (!existsSync(file)) {
    throw new Error(`Missing sub-agent input: ${file}`);
  }
}

const contract = readJson(contractPath, "sub-agent contract");
const runs = readJson(runsPath, "sub-agent runs");

ensure(Array.isArray(contract.subAgents), "contract.subAgents must be an array");
ensure(Array.isArray(runs.agents), "runs.agents must be an array");
ensure(typeof contract.branch === "string" && contract.branch.length > 0, "contract.branch must be set");
ensure(runs.branch === contract.branch, "runs.branch must match contract.branch");
const contractAgents = Array.isArray(contract.subAgents) ? contract.subAgents : [];
const runAgents = Array.isArray(runs.agents) ? runs.agents : [];

ensureUniqueIds(contractAgents, "contract.subAgents");
ensureUniqueIds(runAgents, "runs.agents");

const runByAgent = new Map(runAgents.map(agent => [agent.id, agent]));
const contractIds = new Set(contractAgents.map(agent => agent.id));

for (const agent of runAgents) {
  ensure(contractIds.has(agent.id), `run entry has no matching contract agent: ${agent.id}`);
}

const indexRows = [];
const expectedFiles = new Map();
for (const agent of contractAgents) {
  requireString(agent.id, "contract agent id");
  requireString(agent.lane, `${agent.id}.lane`);
  requireString(agent.mission, `${agent.id}.mission`);
  ensure(Array.isArray(agent.allowedSurfaces) && agent.allowedSurfaces.length > 0, `${agent.id}.allowedSurfaces must be a non-empty array`);
  for (const surface of agent.allowedSurfaces) {
    requireString(surface, `${agent.id}.allowedSurfaces entry`);
  }

  const run = runByAgent.get(agent.id);
  if (!run) {
    failures.push(`Missing run entry for ${agent.id}`);
    continue;
  }
  requireString(run.status, `${agent.id}.status`);
  requireString(run.focus, `${agent.id}.focus`);
  requireString(run.nextAction, `${agent.id}.nextAction`);
  const optionalSections = [
    optionalSection("Status", agent.statusLabel),
    optionalSection("Source Repository", agent.sourceRepository ? `\`${agent.sourceRepository}\`` : ""),
    optionalSection("Canonical Surface", agent.canonicalSurface ? `\`${agent.canonicalSurface}\`` : ""),
    optionalSection("Rollback owner", agent.rollbackOwner ? `\`${agent.rollbackOwner}\`` : ""),
    optionalSection("Purpose", agent.purpose),
    optionalSection("Scope", agent.scope),
    optionalSection("Safety Gate", agent.safetyGate)
  ].filter(Boolean).join("\n");

  const brief = `${GENERATED_NOTICE}

# ${agent.title || titleCase(agent.id)}

## Mission

${agent.mission}

## Current Focus

${run.focus}

## Next Action

${run.nextAction}

## Allowed Surfaces

${agent.allowedSurfaces.map(surface => `- \`${surface}\``).join("\n")}

## Guardrail

Work inside \`${contract.branch}\`; do not create a long-lived branch for this lane.
${optionalSections ? `\n${optionalSections}` : ""}`;

  expectedFiles.set(join(outputDir, `${agent.id}.md`), brief);
  indexRows.push(`| ${agent.id} | ${agent.lane} | ${run.status} | ${run.focus} |`);
}

const index = `${GENERATED_NOTICE}

# UIXAppTTR Sub-Agent Briefs

Run: \`${runs.runId}\`

| Agent | Lane | Status | Focus |
| --- | --- | --- | --- |
${indexRows.join("\n")}
`;

expectedFiles.set(join(outputDir, "README.md"), index);

if (checkMode) {
  for (const [file, expected] of expectedFiles) {
    if (!existsSync(file)) {
      failures.push(`Missing generated sub-agent brief: ${file}`);
      continue;
    }
    const actual = readFileSync(file, "utf8");
    if (actual !== expected) {
      failures.push(`Stale generated sub-agent brief: ${file}`);
    }
  }
  if (existsSync(outputDir)) {
    for (const entry of readdirSync(outputDir)) {
      const file = join(outputDir, entry);
      if (!entry.endsWith(".md") || expectedFiles.has(file)) continue;
      const actual = readFileSync(file, "utf8");
      if (actual.startsWith(GENERATED_NOTICE)) {
        failures.push(`Dangling generated sub-agent brief: ${file}`);
      }
    }
  }
  if (failures.length > 0) {
    console.error("Sub-agent brief check failed:");
    for (const failure of failures) console.error(`- ${failure}`);
    console.error("Run: node scripts/create-subagent-briefs.mjs");
    process.exit(1);
  }
  console.log(`Sub-agent briefs check passed: ${outputDir}`);
} else {
  mkdirSync(outputDir, { recursive: true });
  for (const [file, expected] of expectedFiles) {
    writeFileSync(file, expected);
  }
  console.log(`Sub-agent briefs ready: ${outputDir}`);
}

function titleCase(value) {
  return value
    .split("-")
    .map(part => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ");
}

function optionalSection(title, value) {
  if (!value) return "";
  return `## ${title}\n\n${value}\n`;
}

function readJson(file, label) {
  try {
    return JSON.parse(readFileSync(file, "utf8"));
  } catch (error) {
    throw new Error(`Invalid ${label}: ${file}: ${error.message}`);
  }
}

function requireString(value, label) {
  ensure(typeof value === "string" && value.trim().length > 0, `${label} must be a non-empty string`);
}

function ensureUniqueIds(items, label) {
  const seen = new Set();
  for (const item of items) {
    requireString(item.id, `${label} id`);
    ensure(!seen.has(item.id), `${label} contains duplicate id: ${item.id}`);
    seen.add(item.id);
  }
}

function ensure(condition, message) {
  if (!condition) {
    failures.push(message);
  }
}
